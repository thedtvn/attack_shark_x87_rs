/// Look up a key's LED/matrix index by name (case-insensitive).
pub fn key_index(name: &str) -> Option<u8> {
    KEYS.iter()
        .find(|(n, _)| n.eq_ignore_ascii_case(name))
        .map(|&(_, i)| i)
}
